"""Generate deterministic integer DSP constants; no speech data or model training.

Runtime frontend is integer only. Floating point is used here on the host solely
to derive Hann, FFT twiddle, mel edge and DCT constants from their definitions.
"""
from pathlib import Path
import argparse
import math


def render():
    def array(name, ctype, values, width=12):
        body = '\n'.join('    ' + ', '.join(map(str, values[i:i+width])) + ','
                         for i in range(0, len(values), width))
        return f'static const {ctype} {name}[{len(values)}] = {{\n{body}\n}};\n'

    # Avoid implementation-dependent banker rounding when generating constants.
    def nearest(x):
        return int(math.floor(x + .5)) if x >= 0 else -int(math.floor(-x + .5))

    hann = [nearest((.5 - .5*math.cos(2*math.pi*i/319))*32767)
            for i in range(320)]
    cosine = [nearest(math.cos(2*math.pi*i/512)*32767) for i in range(256)]
    sine = [nearest(-math.sin(2*math.pi*i/512)*32767) for i in range(256)]
    low = 2595*math.log10(1+80/700)
    high = 2595*math.log10(1+7600/700)
    edges = [math.floor((512+1)*700*(10**((low+(high-low)*i/21)/2595)-1)/16000)
             for i in range(22)]
    assert all(a < b for a, b in zip(edges, edges[1:]))
    dct = [nearest(math.cos(math.pi*k*(band+.5)/20)*16384)
           for k in range(1, 13) for band in range(20)]
    return ('/* Generated by gen_tables.py. Mathematical constants, not a model. */\n'
            '#include <stdint.h>\n' +
            array('vp_hann', 'int16_t', hann) +
            array('vp_cos', 'int16_t', cosine) +
            array('vp_sin', 'int16_t', sine) +
            array('vp_mel_edges', 'uint16_t', edges) +
            array('vp_dct', 'int16_t', dct))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = Path(__file__).with_name('feature_tables.inc')
    result = render()
    if args.check:
        assert target.read_text(encoding='utf-8') == result, 'DSP table drift'
    else:
        target.write_text(result, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
