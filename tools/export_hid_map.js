#!/usr/bin/env node
'use strict';
// The author-owned JS table is the only source; this exports resolved data, not new bindings.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..'),src=fs.readFileSync(path.join(root,'game-art/toolkit/prototype/tk_hid.js'),'utf8');
const context=vm.createContext({});vm.runInContext(src,context);const H=context.TKHID;
const quote=(s)=>JSON.stringify(s);
function packet(spec,os) {
  const p=H.resolve(spec,os);
  return !p ? '{0,0,0,NULL}' : `{${{key:1,media:2,text:3}[p.kind]},${p.mod||0},${p.usage||0},${p.text==null?'NULL':quote(p.text)}}`;
}
const binding=(s)=>`{${quote(s?.label||'')},{${packet(s,'mac')},${packet(s,'win')}}}`;
let out=`// Generated by tools/export_hid_map.js; do not edit author defaults here.\n// tk_hid.js SHA256 ${crypto.createHash('sha256').update(src).digest('hex')}\n`;
out+='const tk_binding_t tk_ppt_bindings[5] = {\n'+['prev','next','black','end','start'].map(k=>'    '+binding(H.PPT[k])).join(',\n')+'\n};\n';
out+='const tk_binding_t tk_meeting_bindings[4][3] = {\n'+H.MEET_APPS.map(a=>'    {'+['mute','cam','hand'].map(k=>binding(a[k])).join(',')+'}').join(',\n')+'\n};\n';
out+='const tk_binding_t tk_media_bindings[6] = {\n'+['up','down','ok','long_up','long_down','long_ok'].map(k=>'    '+binding(H.MEDIA_KEYS[k])).join(',\n')+'\n};\n';
out+='const tk_binding_t tk_macro_bindings[6][3] = {\n'+H.MACRO_GROUPS.map(g=>'    {'+['up','ok','down'].map(k=>binding(g[k])).join(',')+'}').join(',\n')+'\n};\n';
out+='const tk_binding_t tk_shutter_binding = '+binding(H.SHUTTER)+';\n';
for(const [name,items] of [['tk_macro_names',H.MACRO_GROUPS.map(g=>g.name)],['tk_meeting_names',H.MEET_APPS.map(a=>a.name)],['tk_os_names',H.OS_LIST.map(os=>H.OS_NAME[os])]])
  out+=`const char *const ${name}[${items.length}] = {${items.map(quote).join(',')}};\n`;
const file=path.join(root,'firmware/main/tk_hid_data.inc');
if(process.argv.includes('--check')) {if(fs.readFileSync(file,'utf8')!==out)throw new Error('Stale C HID table');console.log('Author HID table export: PASS');}
else {fs.writeFileSync(file,out);console.log('Exported '+path.relative(root,file));}
